#!/usr/bin/env python3
"""Generate the C interpreter's opcode table -- from the translator's own sources.

Writes `out/interp_tables.h`: one entry per opcode with its size, addressing mode,
mnemonic id and cycle rule.  Nothing in that header is hand-written, because the
whole point of the exercise is that the interpreter must not own a second opinion
about:

  * **how long an instruction is** (`isa.py` -> the same 256-entry table the
    translator decodes with, so PC advance cannot drift), or
  * **what it costs** (`cycles.py`, shared with the translator's emitted
    `xl_tick(c, N)`).

Usage:  python3 tools/gen_interp_tables.py --out out/interp_tables.h
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
XL = os.path.dirname(HERE)
sys.path.insert(0, XL)

import cycles                                          # noqa: E402
import isa                                             # noqa: E402

# Addressing mode ids -> the C names interp.c uses.  Values come from isa.py, so
# the interpreter cannot disagree with the translator about what mode 7 means.
MODES = [
    ("XMODE_OP", isa.M_OP),
    ("XMODE_OP_A", isa.M_OP_A),
    ("XMODE_NN", isa.M_NN),
    ("XMODE_NN_ZZ", isa.M_NN_ZZ),
    ("XMODE_NN_ZZX", isa.M_NN_ZZX),
    ("XMODE_NN_HHLL", isa.M_NN_HHLL),
    ("XMODE_NN_HHLLX", isa.M_NN_HHLLX),
    ("XMODE_ZZ", isa.M_ZZ),
    ("XMODE_ZZX", isa.M_ZZX),
    ("XMODE_ZZY", isa.M_ZZY),
    ("XMODE_IZZ", isa.M_IZZ),
    ("XMODE_IZZX", isa.M_IZZX),
    ("XMODE_IZZY", isa.M_IZZY),
    ("XMODE_ZZ_HHLL", isa.M_ZZ_HHLL),
    ("XMODE_HHLL", isa.M_HHLL),
    ("XMODE_IHHLL", isa.M_IHHLL),
    ("XMODE_HHLLX", isa.M_HHLLX),
    ("XMODE_HHLLY", isa.M_HHLLY),
    ("XMODE_BLOCK", isa.M_BLOCK),
    ("XMODE_BRANCH", isa.M_BRANCH_OR_LABEL),
    ("XMODE_ZZ_REL", isa.M_ZZ_LABEL),
    ("XMODE_IHHLLX", isa.M_IHHLLX),
    ("XMODE_DB", isa.M_DB),
]

RULES = [("XK_FIXED", cycles.RULE_FIXED), ("XK_BRANCH", cycles.RULE_BRANCH),
         ("XK_BITBRANCH", cycles.RULE_BITBRANCH), ("XK_BLOCK", cycles.RULE_BLOCK)]


class Probe:
    """Just enough of an `Ins` for cycles.cycle_rule()."""

    __slots__ = ("mnem", "mode", "block")

    def __init__(self, mnem, mode):
        self.mnem, self.mode, self.block = mnem, mode, (0, 0, 0)


def c_name(mnem):
    return "XM_" + re.sub(r"[^A-Z0-9]", "", mnem.upper())


def build():
    mnemonics = sorted({name.strip() for name, _s, _m in isa.TABLE})
    mnems = {m: i for i, m in enumerate(mnemonics)}

    # interp.c derives a bit number by subtraction from these groups, so they must
    # be consecutive in the generated enum.  A build failure here is the honest
    # outcome if the opcode table ever stops being alphabetical.
    for group in ("rmb", "smb", "bbr", "bbs"):
        ids = [mnems[group + str(b)] for b in range(8)]
        if ids != list(range(ids[0], ids[0] + 8)):
            raise SystemExit("gen_interp_tables: %s0-7 are not contiguous" % group)
    for pair in (("bbr0", "bbr7"), ("bbs0", "bbs7")):
        if mnems[pair[1]] - mnems[pair[0]] != 7:
            raise SystemExit("gen_interp_tables: %s..%s not contiguous" % pair)
    if mnems["bbs7"] - mnems["bbr0"] != 15:
        raise SystemExit("gen_interp_tables: bbr0..bbs7 are not one run")

    rows = []
    for op, (name, size, mode) in enumerate(isa.TABLE):
        mnem = name.strip()
        kind, a, b = cycles.cycle_rule(Probe(mnem, mode))
        rows.append((op, mnem, size, mode, kind, a, b))
    return mnemonics, rows


def render(mnemonics, rows):
    out = ["/* Generated by src/tools/gen_interp_tables.py -- do not edit.",
           " *",
           " * Source of truth: isa.py's opcode table (name/size/mode, the one the",
           " * translator decodes with) and cycles.py (costs, the one the translator",
           " * emits).  Regenerate with ./build.sh; never edit by hand. */",
           "#ifndef XLATE_INTERP_TABLES_H",
           "#define XLATE_INTERP_TABLES_H",
           "",
           "/* Addressing modes (values from isa.py). */"]
    for name, value in MODES:
        out.append("#define %-18s %d" % (name, value))
    out.append("")
    out.append("/* Cycle rule kinds (values from cycles.py). */")
    for name, value in RULES:
        out.append("#define %-18s %d" % (name, value))
    out.append("")
    out.append("/* Mnemonics, alphabetical.  rmb0-7, smb0-7, bbr0-7 and bbs0-7 are")
    out.append("   consecutive runs; interp.c relies on that and the generator asserts")
    out.append("   it. */")
    out.append("enum {")
    for i, m in enumerate(mnemonics):
        end = "," if i + 1 < len(mnemonics) else ""
        out.append("    %-10s = %d%s" % (c_name(m), i, end))
    out.append("};")
    out.append("")
    out.append("typedef struct XOp {")
    out.append("    unsigned char size;   /* instruction length, bytes */")
    out.append("    unsigned char mode;   /* XMODE_* */")
    out.append("    unsigned char mnem;   /* XM_* */")
    out.append("    unsigned char kind;   /* XK_* */")
    out.append("    short a;              /* cost | taken | base */")
    out.append("    short b;              /* --   | not   | per byte */")
    out.append("} XOp;")
    out.append("")
    out.append("static const XOp xl_ops[256] = {")
    for (op, mnem, size, mode, kind, a, b) in rows:
        mname = next(n for n, v in MODES if v == mode)
        kname = next(n for n, v in RULES if v == kind)
        out.append("    { %d, %-16s %-10s %-12s %2d, %2d },  /* %02X %s */"
                   % (size, mname + ",", c_name(mnem) + ",", kname + ",", a, b, op, mnem))
    out.append("};")
    out.append("")
    out.append("#endif /* XLATE_INTERP_TABLES_H */")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    mnemonics, rows = build()
    path = a.out
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        f.write(render(mnemonics, rows))
    kinds = {}
    for (_op, _m, _s, _md, kind, _a, _b) in rows:
        kinds[kind] = kinds.get(kind, 0) + 1
    print("wrote %s (%d opcodes, %d mnemonics; fixed=%d branch=%d bitbranch=%d block=%d)"
          % (path, len(rows), len(mnemonics),
             kinds.get(cycles.RULE_FIXED, 0), kinds.get(cycles.RULE_BRANCH, 0),
             kinds.get(cycles.RULE_BITBRANCH, 0), kinds.get(cycles.RULE_BLOCK, 0)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
